#!/usr/bin/env python3
"""
Download the Arabic font families used by Talib from Google Fonts and bundle them
locally (spec section 1: "Fonts ... bundled locally (no CDN at runtime)").

Every family is OFL / open-licensed, so redistribution inside the APK is fine.
Each @font-face block is kept verbatim (unicode-range included) so the browser
still picks the right subset for Arabic vs Latin digits.
"""
import os
import re
import sys
import urllib.request

OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "fonts")
CSS_OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "fonts.css")

UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
)

# family -> weights we actually ship
FAMILIES = {
    "Amiri": "400;700",
    "Noto+Naskh+Arabic": "400;600;700",
    "IBM+Plex+Sans+Arabic": "400;500;600;700",
    "Reem+Kufi": "400;500;600;700",
    "Tajawal": "400;500;700;800",
    "Cairo": "400;500;600;700;900",
    "Scheherazade+New": "400;500;700",
    "Noto+Kufi+Arabic": "400;600;700",
}

URL = (
    "https://fonts.googleapis.com/css2?"
    + "&".join(f"family={fam.replace(' ', '+')}:wght@{w}" for fam, w in FAMILIES.items())
    + "&display=swap"
)


def get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return resp.read()


def main() -> int:
    os.makedirs(OUT_DIR, exist_ok=True)
    css = get(URL).decode("utf-8")

    blocks = re.findall(r"/\*\s*([\w\-\[\]]+)\s*\*/\s*(@font-face\s*\{.*?\})", css, re.S)
    if not blocks:
        print("FATAL: no @font-face blocks parsed from Google Fonts CSS", file=sys.stderr)
        print(css[:800], file=sys.stderr)
        return 1

    seen = {}
    out_css = [
        "/* Talib bundled fonts - generated by design/tools/fetch_fonts.py",
        "   All families are open-licensed (OFL). Do not edit by hand. */",
        "",
    ]

    for subset, block in blocks:
        fam = re.search(r"font-family:\s*'([^']+)'", block).group(1)
        weight = re.search(r"font-weight:\s*(\d+)", block)
        weight = weight.group(1) if weight else "400"
        style = re.search(r"font-style:\s*(\w+)", block)
        style = style.group(1) if style else "normal"
        url_m = re.search(r"url\((https://[^)]+\.woff2)\)", block)
        if not url_m:
            continue
        src = url_m.group(1)

        slug = re.sub(r"[^a-zA-Z0-9]+", "-", fam).strip("-").lower()
        fname = f"{slug}-{weight}-{style}-{subset}.woff2"
        path = os.path.normpath(os.path.join(OUT_DIR, fname))

        if fname not in seen:
            data = get(src)
            with open(path, "wb") as fh:
                fh.write(data)
            seen[fname] = len(data)
            print(f"  saved {fname}  ({len(data)/1024:.0f} KB)")

        block = block.replace(url_m.group(0), f"url('./fonts/{fname}')")
        block = re.sub(r"\n\s*", "\n  ", block).strip()
        out_css.append(block)
        out_css.append("")

    with open(CSS_OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out_css))

    total = sum(seen.values())
    print(f"\n{len(seen)} font files, {total/1024/1024:.2f} MB total")
    print(f"css -> {CSS_OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
